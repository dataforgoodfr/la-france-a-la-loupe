import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import postcss from "postcss";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const projectDir = path.resolve(scriptDir, "..");
const inputFile = path.join(projectDir, "src", "styles", "tokens-extracted.css");
const outputFile = path.join(projectDir, "src", "styles", "tokens.css");

const BREAKPOINT = "48rem";

// Font families are injected by Astro (see astro.config.mjs); do not redeclare them.
const astroFontVariables = new Set([
  "--font-family-anton",
  "--font-family-montserrat",
  "--font-family-libre-baskerville",
]);

const banner = [
  "Design tokens, mobile-first.",
  "   Source: src/styles/tokens-extracted.css (Figma variables2css export).",
  "   Generated by webapp/scripts/build-tokens.ts; do not edit by hand.",
  "   Run `npm run tokens` after re-extracting the tokens from Figma.",
].join("\n");

const divider = `Desktop overrides (>= ${BREAKPOINT} / 768px)`;

const parsed = postcss.parse(fs.readFileSync(inputFile, "utf8"));

type Token = { name: string; value: string };
const base: Token[] = [];
const desktop: Token[] = [];
const mobileByBase = new Map<string, string>();

function isMobile(name: string): boolean {
  return name.startsWith("--mobile-") || name.endsWith("-mobile");
}

function isDesktop(name: string): boolean {
  return name.startsWith("--desktop-") || name.endsWith("-desktop");
}

function stripVariant(name: string): string {
  return name.replace(/^--(?:mobile|desktop)-/, "--").replace(/-(?:mobile|desktop)$/, "");
}

for (const rule of parsed.nodes) {
  if (rule.type !== "rule") continue;
  for (const node of rule.nodes) {
    if (node.type !== "decl") continue;
    if (astroFontVariables.has(node.prop)) continue;
    const token = { name: stripVariant(node.prop), value: node.value.trim() };
    if (isMobile(node.prop)) {
      base.push(token);
      mobileByBase.set(token.name, token.value);
    } else if (isDesktop(node.prop)) {
      desktop.push(token);
    } else {
      base.push(token);
    }
  }
}

// Skip a desktop override when it matches the mobile default.
const overrides = desktop.filter((token) => mobileByBase.get(token.name) !== token.value);

// Write tokens.css

const root = postcss.root();

const bannerComment = postcss.comment({ text: banner });
const baseRule = postcss.rule({ selector: ":root" });
baseRule.raws.semicolon = true;
for (const token of base) {
  baseRule.append(postcss.decl({ prop: token.name, value: token.value }));
}

const dividerComment = postcss.comment({ text: divider });

const media = postcss.atRule({
  name: "media",
  params: `(width >= ${BREAKPOINT})`,
});
const desktopRule = postcss.rule({ selector: ":root" });
desktopRule.raws.semicolon = true;
for (const token of overrides) {
  desktopRule.append(postcss.decl({ prop: token.name, value: token.value }));
}
media.append(desktopRule);

root.append(bannerComment, baseRule, dividerComment, media);
root.raws.after = "\n";

const output = root.toString();
const previous = fs.existsSync(outputFile) ? fs.readFileSync(outputFile, "utf8") : "";
fs.writeFileSync(outputFile, output, "utf8");

const relativeOutput = path.relative(projectDir, outputFile);
console.log(
  previous === output ? `${relativeOutput} is already up to date` : `Wrote ${relativeOutput}`,
);
console.log(`  ${base.length} base tokens, ${overrides.length} desktop overrides`);
